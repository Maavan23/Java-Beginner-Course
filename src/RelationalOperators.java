class RelationalOperators {
    public static void main(MainForString[] args) {
        int number1 = 12;
        int number2 = 15;

        // is equal to
        System.out.println(number1 == number2);

        // is not equal to
        System.out.println(number1 != number2);

        // is greater than
        System.out.println(number1 > number2);

        // is less than
        System.out.println(number1 < number2);

        // is greater than or equal to
        System.out.println(number1 >= number2);

        // is less than or equal to 
        System.out.println(number1 <= number2);
    }    
}
